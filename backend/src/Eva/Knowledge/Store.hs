{-# LANGUAGE OverloadedStrings #-}

-- | CRUD functions for knowledge_entries.
-- The FTS index (knowledge_fts) is maintained entirely by the 3 sync triggers
-- created in Eva.Persistence.Migration — this module never queries FTS directly.
module Eva.Knowledge.Store
  ( insertEntry
  , updateEntry
  , deleteEntry
  , getEntry
  , listEntries
  , listBySource
  , deleteNonEditedBySource
  , resetToAutoGenerated
  ) where

import Control.Monad.IO.Class (liftIO)
import Data.Aeson (FromJSON, ToJSON, eitherDecodeStrict, encode, toJSON)
import Data.Aeson.Types (parseEither, parseJSON)
import qualified Data.ByteString.Lazy as BL
import Data.Text (Text)
import qualified Data.Text as T
import qualified Data.Text.Encoding as TE
import Data.Time (getCurrentTime)
import Database.Persist.Sql
